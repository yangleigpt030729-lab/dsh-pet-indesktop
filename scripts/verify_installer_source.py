"""Bind v1.0.1 to a fresh source build, including actual frozen repair modules.

Receipts are build evidence, not a signature/certification of an untrusted ZIP.
The supported installer entry always creates the build itself; no ZIP input exists.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
from types import CodeType
import zipfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts import package_companion_test as source_package
from scripts.verify_installer_payload import EXE, VERSION

MODULES = ('pet.speech_binding', 'pet.manual_screen_speech', 'pet.character_names',
           'pet.chat.legacy_widgets', 'pet.chat.widgets', 'pet.chat.service',
           'pet.voice_chime_quotes', 'pet.voice_chime_service')


def sha256(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def code_signature(code):
    """Compare executable code without build-machine filenames or marshal interning."""
    if not isinstance(code, CodeType):
        if isinstance(code, tuple):
            return tuple(code_signature(item) for item in code)
        if isinstance(code, frozenset):
            return ('frozenset', tuple(sorted(repr(item) for item in code)))
        return (type(code).__name__, repr(code))
    return (code.co_code, tuple(code_signature(item) for item in code.co_consts),
            code.co_names, code.co_varnames, code.co_freevars, code.co_cellvars,
            code.co_argcount, code.co_posonlyargcount, code.co_kwonlyargcount,
            code.co_flags, code.co_stacksize, code.co_nlocals, code.co_name, code.co_qualname, code.co_exceptiontable)


def verify_frozen(pyz, sources):
    hashes = {}
    modules = set(MODULES) | {name for name in pyz.toc if name == 'pet' or name.startswith('pet.')}
    for module in sorted(modules):
        path = module.replace('.', '/') + '.py'
        if path not in sources:
            path = module.replace('.', '/') + '/__init__.py'
        if path not in sources:
            raise ValueError('Frozen application module has no reviewed source: ' + module)
        data = sources[path]
        expected = compile(data, path, 'exec', optimize=0)
        if module not in pyz.toc or code_signature(pyz.extract(module)) != code_signature(expected):
            raise ValueError('Frozen repair module differs from reviewed source: ' + module)
        hashes[path] = hashlib.sha256(data).hexdigest()
    return hashes


def inspect_build(root, work):
    root, work = Path(root).resolve(), Path(work).resolve()
    if work == root or work.is_relative_to(root) or root.is_relative_to(work):
        raise ValueError('Build must be outside the original source')
    archive_path = work/'reviewed-source.zip'
    source_package.verify(archive_path)
    with zipfile.ZipFile(archive_path) as archive:
        manifest = json.loads(archive.read(source_package.PREFIX+source_package.MANIFEST))['files']
        current = {name: sha256(path) for name, path in source_package.source_files(root)}
        if current != manifest:
            raise ValueError('Current source differs from the fresh build source archive')
        stage = work/'dsh-pet-companion-win10'
        # Only the icon is regenerated by the existing native onedir workflow.
        for name, digest in manifest.items():
            if name != 'assets/icon.ico' and sha256(stage/name) != digest:
                raise ValueError('Staged build source changed: ' + name)
        sources = {name:archive.read(source_package.PREFIX+name) for name in manifest
                   if name.startswith('pet/') and name.endswith('.py')}
    from PyInstaller.archive.readers import CArchiveReader
    exe = stage/'dist-onedir'/'dsh-pet-standalone-webm-chat'/EXE
    reader = CArchiveReader(str(exe))
    pyzs = [reader.open_embedded_archive(name) for name, entry in reader.toc.items() if entry[-1]=='z']
    if len(pyzs) != 1:
        raise ValueError('Expected one authoritative frozen PYZ')
    hashes = verify_frozen(pyzs[0], sources)
    portable = stage/'dist-onedir'/'dsh-pet-standalone-webm-chat-portable.zip'
    with zipfile.ZipFile(portable) as archive:
        # The actual generated ZIP is root EXE + _internal, never a guessed wrapper.
        with archive.open(EXE) as stream:
            if hashlib.file_digest(stream, 'sha256').hexdigest() != sha256(exe):
                raise ValueError('Portable EXE differs from the fresh native build')
    return {'format':1, 'version':VERSION, 'source_archive_sha256':sha256(archive_path),
            'source_files':len(manifest), 'repair_source_sha256':hashes,
            'portable_sha256':sha256(portable), 'exe_sha256':sha256(exe),
            'python':sys.version.split()[0], 'native_setup':'NOT BUILT by source verification'}


def record(root, work, receipt):
    receipt = Path(receipt)
    if receipt.exists():
        raise FileExistsError('Source build receipt already exists')
    report = inspect_build(root, work)
    report['verified_utc'] = datetime.now(timezone.utc).isoformat()
    with receipt.open('x', encoding='utf-8') as stream:
        json.dump(report, stream, ensure_ascii=False, sort_keys=True, indent=2)
    return report


def verify(root, work, receipt):
    saved = json.loads(Path(receipt).read_text(encoding='utf-8'))
    current = inspect_build(root, work)
    if {key:saved.get(key) for key in current} != current:
        raise ValueError('Source/native build provenance changed after verification')
    return saved


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--receipt', type=Path, required=True)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    try:
        result = (verify if args.verify else record)(args.source, args.work, args.receipt)
        print(f"PASS: v{VERSION} source/native ZIP provenance; {result['source_files']} source files; {len(result['repair_source_sha256'])} frozen application modules")
    except (OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
        print(f'FAIL: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
